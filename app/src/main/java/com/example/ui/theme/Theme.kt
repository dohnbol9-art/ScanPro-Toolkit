@Composable
fun ScanProTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false, // Preserve our calibrated precision theme by default
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> ScanProDarkColorScheme
        else -> ScanProLightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = ScanProTypography,
        content = content
    )
}

// Keep backward compatible name for existing template references
@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    ScanProTheme(darkTheme = darkTheme, dynamicColor = dynamicColor, content = content)
}
